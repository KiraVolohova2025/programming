# Средствами языка Python сформировать текстовый файл,
#  содержащий последовательность из целых положительных
#  и отрицательных чисел. сформировать новый текстовый файл
#  следующего вида, предварительно выполнив требуемую 
# обработку элементов: 
# исходные данные: 
# количество элементов: 
# Минимальный элемент: 
# Квадраты четных элементов: 
# сумма квадратов четных элементов: 
# среднее арифметическое суммы квадратов четных элеменентов:

# Создаю новый файл и записываю в него числа
numbers = [-1, 2, 3, 4, -5, 6]  # список чисел

f1 = open('text1.txt', 'w', encoding="UTF-8")
# Преобразую числа в строку с пробелами
f1.write(" ".join(map(str, numbers)))
f1.close()

# Обрабатываю данные
count = len(numbers)
min_el = min(numbers)

# Нахожу четные элементы и их квадраты
ch_el = [x for x in numbers if x % 2 == 0]  # проверяю на четность
k_el = [x ** 2 for x in ch_el]
summa_k_el = sum(k_el)

# Нахожу среднее значение суммы квадратов четных элементов
if len(ch_el) > 0:
    avarage = summa_k_el / len(ch_el)
else:
    avarage = 0

# Записываю результаты в новый файл
f2 = open('result.txt', 'w', encoding="UTF-8")  # Новый файл для результатов
f2.write(f"Исходные данные: {' '.join(map(str, numbers))}\n")
f2.write(f"Количество элементов: {count}\n")
f2.write(f"Минимальный элемент: {min_el}\n")
f2.write(f"Квадраты четных элементов: {' '.join(map(str, k_el))}\n")
f2.write(f"Сумма квадратов четных элементов: {summa_k_el}\n")
f2.write(f"Среднее арифметическое суммы квадратов четных элементов: {avarage:.2f}\n")
f2.close()

# Вывожу результат
print("Результаты сохранены в файл result.txt")

# Проверяю содержимое созданного файла
print("\nСодержимое result.txt:")
f3 = open("result.txt", "r", encoding="UTF-8")
print(f3.read())
f3.close()