# Размер скидки на продукты определен следующим образом:
# при покупке до 500р скидка составит 2%. При покупке от 500р до 1000р
# скидка составит 4%. При покупке от 1500р до 2000р скидка составит 5%.
# Составить программу, определяющую размер скидки в зависимости от
# потраченной суммы.

# Ввожу переменную для хранения суммы покупки,
# будет использоваться после цикла
total_amount = 0.0

# Ввожу флаг отслеживания для того, что если пользователь
# введет "выход", этот флаг станет False.
proceed_calculation = True

# Цикл для повторного запроса ввода до получения корректных данных
while True:
    try:
        # Запрашиваем сумму покупки у пользователя
        amount = input("Введите общую сумму покупки в рублях (или 'выход' для завершения): ")

        # Проверка, хочет ли пользователь выйти из программы
        if amount.lower() == 'выход':
            print("Программа завершена.")
            proceed_calculation = False  # Устанавливаем флаг False для завершения программы
            break

        # Преобразую сумму покупки в число с плавающей точкой
        total_amount = float(amount)

        # Проверяю, что сумма не отрицательная
        if total_amount < 0:
            print("Ошибка: Сумма покупки не может быть отрицательной. Пожалуйста, введите корректное значение.")
            continue

        break

    except ValueError:
        # Обработка ошибки, если ввели не число
        print("Ошибка ввода: Пожалуйста, вводите числовые значения для суммы покупки.")
        continue

# Расчеты и вывод результата будет выполнен только если пользователь не ввел "выход"
if proceed_calculation:
    # Определение размера скидки в зависимости от суммы
    discount_percent = 0  # По умолчанию скидка 0%

    if total_amount < 500:
        discount_percent = 2
    elif 500 <= total_amount < 1000:
        discount_percent = 3
    elif 1000 <= total_amount < 1500:
        discount_percent = 4
    elif 1500 <= total_amount <= 2000:
        discount_percent = 5
    else:
        # Если сумма больше 2000, применю максимальную скидку
        discount_percent = 5
        print("Примечание: Сумма покупки превышает 2000 рублей. Применена максимальная скидка 5%.")

    # Вычисление суммы скидки и итоговой суммы
    discount_amount = total_amount * (discount_percent / 100)
    final_amount = total_amount - discount_amount

    # Вывод результатов
    print(f"\nСумма вашей покупки: {total_amount:.2f} руб.")
    print(f"Примененная скидка: {discount_percent}%")
    print(f"Сумма скидки: {discount_amount:.2f} руб.")
    print(f"Итого к оплате: {final_amount:.2f} руб.")